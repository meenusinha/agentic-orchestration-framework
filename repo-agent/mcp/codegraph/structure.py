"""Repo structure: role of every file, build targets (processes / libraries) and
generated-code provenance.

Precedence: the developer's manifest (`structure:` in mcp/config.yaml) → build
facts (compile_commands.json, Makefiles, CMakeLists.txt) → folder/file heuristics.

Build files are only READ. Running `make -pn` or a CMake configure step can
execute arbitrary commands from the repo, so this module never runs them.
"""
from __future__ import annotations

import fnmatch
import glob
import json
import os
import re
import shlex
from dataclasses import dataclass, field
from pathlib import Path, PurePosixPath

# ── heuristics ────────────────────────────────────────────────────────────────
_DIR_ROLES = [
    ({"external", "extern", "third_party", "thirdparty", "third-party", "vendor", "vendors", "deps", "contrib",
      "3rdparty", "submodules"}, "external"),
    ({"gen", "generated", "autogen", "auto_generated", "codegen"}, "generated"),
    ({"test", "tests", "unittest", "unittests", "unit_tests", "__tests__", "spec", "specs", "testing",
      "integration_tests", "e2e", "ctest"}, "test"),
    ({"include", "inc", "api", "public", "interface", "interfaces", "idl", "idls", "proto", "protos",
      "contracts", "headers"}, "interface"),
    ({"internal", "private", "impl", "detail", "details"}, "internal"),
    ({"doc", "docs", "documentation", "knowledge", "adr", "adrs", "wiki"}, "docs"),
    ({"tools", "tool", "scripts", "script", "utils", "util", "bin"}, "tooling"),
    ({"examples", "example", "demo", "demos", "samples", "sample", "benchmarks", "bench"}, "example"),
    ({"cmake", "make", "build_tools", "ci", ".github"}, "build"),
]
_TEST_FILE = re.compile(r"(^test_.*|.*_test\.[^.]+$|.*_tests\.[^.]+$|.*Test\.(java|cs|kt)$|.*\.(test|spec)\.[jt]sx?$|^t_.*)",
                        re.I)
_BUILD_FILES = {"makefile", "gnumakefile", "cmakelists.txt", "meson.build", "build.gradle", "pom.xml",
                "compile_commands.json",
                "package.json", "cargo.toml", "go.mod", "build", "build.bazel", "sconstruct"}
_GENERATED_MARK = re.compile(r"(generated by|do not edit|auto-?generated|automatically generated|"
                             r"this file (was|is) generated|@generated|code generated)", re.I)
# file-name shapes IDL compilers produce: stem + suffix (TAO, omniORB, protoc, Fast-DDS, RTI, thrift, MIDL…)
_GEN_SUFFIXES = ("C", "S", "S_T", "C_T", "_skel", "_stub", "Sk", "SK", "_s", "_c", "_i", "_p", ".pb", "_pb2",
                 "_pb2_grpc", ".grpc.pb", "PubSubTypes", "TypeObjectSupport", "CdrAux", "Plugin", "Support",
                 "_types", "_constants", "_server", "_client", "Impl_gen", "_h", "_i_c", "_dlldata", "_proxy",
                 "Types", "TypeSupport", "TypeSupportImpl", "TypeSupportC", "TypeSupportS")
_IDL_COMPILERS = re.compile(r"\b(tao_idl|omniidl|idl2cpp|idlcpp|midl|protoc|fastddsgen|fastrtpsgen|rtiddsgen|"
                            r"idlc|idlpp|opendds_idl|thrift|rosidl\w*|flatc|capnp|sidl|idl)\b")


@dataclass
class Target:
    name: str
    kind: str                       # executable / library
    defined_in: str                 # build file (repo-relative)
    sources: set = field(default_factory=set)
    links: set = field(default_factory=set)


@dataclass
class Structure:
    roles: dict = field(default_factory=dict)          # file → role
    visibility: dict = field(default_factory=dict)     # file → public/internal (from manifest)
    index_mode: dict = field(default_factory=dict)     # file → full / signatures / skip
    generated: dict = field(default_factory=dict)      # file → reason
    generated_from: dict = field(default_factory=dict)  # generated file → idl file
    targets: dict = field(default_factory=dict)        # name → Target
    file_targets: dict = field(default_factory=dict)   # file → [target names]
    lang_override: dict = field(default_factory=dict)  # file → c / cpp (from compile db)
    from_manifest: set = field(default_factory=set)    # files whose role the developer set explicitly


def resolve(repo_root: Path, files: list[str], manifest: list | None = None) -> Structure:
    """`files`: repo-relative paths (POSIX) that will be indexed."""
    st = Structure()
    fileset = set(files)
    by_stem: dict[str, list[str]] = {}
    for f in files:
        by_stem.setdefault(PurePosixPath(f).stem, []).append(f)

    _compile_db(repo_root, fileset, st)
    for bf in _find_build_files(repo_root):
        name = bf.name.lower()
        try:
            if name in ("makefile", "gnumakefile") or bf.suffix in (".mk", ".mak"):
                _makefile(repo_root, bf, fileset, by_stem, st)
            elif name == "cmakelists.txt":
                _cmake(repo_root, bf, fileset, st)
        except (OSError, RecursionError, ValueError):
            continue
    idl_files = [f for f in files if PurePosixPath(f).suffix.lower() in
                 (".idl", ".pidl", ".midl", ".proto", ".thrift", ".msg", ".srv", ".fidl", ".aidl")]
    for f in files:
        reason = _generated_reason(repo_root / f, f)
        if reason:
            st.generated[f] = reason
        src = _generated_source(f, idl_files)
        if src and f not in idl_files:
            st.generated_from[f] = src
            st.generated.setdefault(f, f"name matches {src}")
    for f in files:
        st.roles[f] = _role(f, manifest or [], st)
    for t in st.targets.values():
        for s in t.sources:
            st.file_targets.setdefault(s, []).append(t.name)
        if t.sources and all(st.roles.get(s) == "test" for s in t.sources):
            t.kind = "test"                             # test runner, not a product process
    return st


def _role(f: str, manifest: list, st: Structure) -> str:
    for entry in manifest:                              # 1. developer's manifest wins
        pat = entry.get("path", "")
        if pat and (fnmatch.fnmatch(f, pat) or fnmatch.fnmatch(f, pat.rstrip("/") + "/**") or
                    f.startswith(pat.rstrip("*").rstrip("/") + "/")):
            if entry.get("visibility"):
                st.visibility[f] = entry["visibility"]
            if entry.get("index"):
                st.index_mode[f] = entry["index"]
            st.from_manifest.add(f)
            return entry.get("role", "implementation")
    if f in st.generated:                               # 2. build / content facts
        return "generated"
    p = PurePosixPath(f)
    if p.name.lower() in _BUILD_FILES or p.suffix in (".mk", ".mak", ".cmake"):
        return "build"
    if _TEST_FILE.match(p.name):
        return "test"
    for part in [x.lower() for x in p.parts[:-1]]:      # 3. folder heuristics, outermost first
        for names, role in _DIR_ROLES:
            if part in names:
                if role == "external":
                    st.index_mode.setdefault(f, "signatures")
                return role
    if p.suffix.lower() in (".idl", ".proto", ".thrift", ".msg", ".srv", ".fidl", ".aidl", ".midl"):
        return "interface"
    if p.suffix.lower() in (".md", ".markdown", ".rst", ".txt", ".adoc"):
        return "docs"
    return "implementation"


def _generated_reason(path: Path, rel: str) -> str:
    try:
        with open(path, "rb") as fh:
            head = fh.read(2048).decode("utf-8", "replace")
    except OSError:
        return ""
    m = _GENERATED_MARK.search(head)
    return f"header says '{m.group(0)}'" if m else ""


def _generated_source(f: str, idl_files: list[str]) -> str:
    """foo.idl → fooC.h, fooS.cpp, foo.pb.cc, fooPubSubTypes.cxx, foo_skel.c …"""
    stem = PurePosixPath(f).name.split(".")[0]
    best = ""
    for idl in idl_files:
        istem = PurePosixPath(idl).stem
        if stem == istem and PurePosixPath(f).suffix.lower() not in (".idl", ".proto", ".thrift"):
            best = best or idl
            continue
        for suf in _GEN_SUFFIXES:
            if stem == istem + suf.lstrip(".") or stem == istem + suf:
                return idl
    return best if best and PurePosixPath(f).suffix.lower() in (".h", ".hh", ".hpp", ".cpp", ".cc", ".cxx", ".c",
                                                                 ".py", ".java", ".cs", ".go", ".rs", ".ts", ".js") \
        else ""


def _find_build_files(root: Path, max_depth: int = 6):
    for dp, dn, fns in os.walk(root):
        rel_depth = len(Path(dp).relative_to(root).parts)
        dn[:] = [d for d in dn if not d.startswith(".") and d not in ("node_modules", "venv", ".venv", "__pycache__")
                 and rel_depth < max_depth]
        for fn in fns:
            if fn.lower() in ("makefile", "gnumakefile", "cmakelists.txt") or fn.endswith((".mk", ".mak")):
                yield Path(dp) / fn


# ── compile_commands.json ─────────────────────────────────────────────────────
def _compile_db(root: Path, fileset: set, st: Structure):
    for cand in [root / "compile_commands.json"] + sorted(root.glob("*/compile_commands.json")) + \
            sorted(root.glob("*/*/compile_commands.json")):
        try:
            entries = json.loads(cand.read_text())
        except (OSError, ValueError):
            continue
        for e in entries if isinstance(entries, list) else []:
            src = Path(e.get("directory", ".")) / e.get("file", "")
            try:
                rel = src.resolve().relative_to(root.resolve()).as_posix()
            except ValueError:
                continue
            args = e.get("arguments") or shlex.split(e.get("command", ""), posix=True)
            compiler = PurePosixPath(args[0]).name if args else ""
            if "-x" in args:
                lang = args[args.index("-x") + 1] if args.index("-x") + 1 < len(args) else ""
                st.lang_override[rel] = "cpp" if "c++" in lang else "c"
            elif re.search(r"(\+\+|xx|clang\+\+|cl\.exe)$", compiler) or compiler in ("c++", "g++", "clang++"):
                st.lang_override[rel] = "cpp"
            elif compiler in ("cc", "gcc", "clang") or compiler.endswith(("-gcc", "-cc")):
                st.lang_override[rel] = "c"
        return                                          # first database found wins


# ── Makefiles (static) ────────────────────────────────────────────────────────
_ASSIGN = re.compile(r"^\s*(?:override\s+|export\s+)?([A-Za-z_][A-Za-z0-9_.\-]*)\s*([:+?!]?=|::=)\s*(.*)$")
_RULE = re.compile(r"^([^\t#=][^=]*?)\s*:(?!=)\s*(.*)$")


def _makefile(root: Path, mf: Path, fileset, by_stem, st: Structure, variables=None, depth=0):
    if depth > 4:
        return
    text = re.sub(r"\\\n", " ", mf.read_text(errors="replace"))
    vars_ = dict(variables or {})
    rules = []                                          # (targets, prereqs, recipe)
    cur = None
    for line in text.splitlines():
        if line.startswith("\t"):
            if cur is not None:
                cur[2].append(line.strip())
            continue
        s = line.split("#", 1)[0].rstrip()
        if not s.strip():
            continue
        m = _ASSIGN.match(s)                            # NAME op value  (rules never match: no ':' in NAME)
        if m:
            name, op, val = m.groups()
            val = _expand(val, vars_, mf.parent) if op in (":=", "::=") else val
            vars_[name] = (vars_.get(name, "") + " " + val).strip() if op == "+=" else \
                (vars_.get(name, val) if op == "?=" else val)
            cur = None
            continue
        inc = re.match(r"^\s*-?s?include\s+(.+)$", s)
        if inc:
            for path in _expand(inc.group(1), vars_, mf.parent).split():
                for p in glob.glob(str(mf.parent / path)):
                    _makefile(root, Path(p), fileset, by_stem, st, vars_, depth + 1)
            continue
        r = _RULE.match(s)
        if r and not s.lstrip().startswith(("ifeq", "ifneq", "ifdef", "ifndef", "else", "endif", "define")):
            cur = (r.group(1), r.group(2), [])
            rules.append(cur)
    rel_mf = mf.relative_to(root).as_posix()
    for targets_s, prereqs_s, recipe in rules:
        targets = _expand(targets_s, vars_, mf.parent).split()
        prereqs = _expand(prereqs_s.split(";")[0], vars_, mf.parent).split()
        recipe_x = " ".join(_expand(r, vars_, mf.parent) for r in recipe)
        for sub in re.findall(r"\$\(MAKE\)\s+-C\s+(\S+)|make\s+-C\s+(\S+)", recipe_x):
            d = mf.parent / (sub[0] or sub[1])
            for name in ("Makefile", "makefile", "GNUmakefile"):
                if (d / name).is_file():
                    _makefile(root, d / name, fileset, by_stem, st, None, depth + 1)
                    break
        for t in targets:
            if t.startswith(".") or "%" in t or t in ("all", "clean", "install", "test", "check", "distclean"):
                continue
            tname = PurePosixPath(t).name
            if tname.endswith((".o", ".obj", ".d", ".h", ".hh", ".c", ".cpp", ".cc")):
                continue
            if not re.search(r"\$\(?(CC|CXX|LD|AR)\)?|\b(gcc|g\+\+|clang\+\+?|cc|c\+\+|ld|ar|link)\b|-o\s+\$@",
                             recipe_x + " " + " ".join(recipe)):
                continue
            kind = "library" if (re.match(r"^lib.*|.*\.(a|so|dylib|lib|dll)(\.\d+)*$", tname) or
                                 re.search(r"(^|\s)-shared\b|\$\(AR\)|\bar\s+r", recipe_x)) else "executable"
            tgt = st.targets.setdefault(tname, Target(tname, kind, rel_mf))
            for p in prereqs:
                for src in _sources_for(p, mf.parent, root, fileset, by_stem):
                    tgt.sources.add(src)
            tgt.links.update(re.findall(r"(?:^|\s)-l([A-Za-z0-9_+\-.]+)", recipe_x))
            tgt.links.update(PurePosixPath(p).name for p in prereqs if re.search(r"\.(a|so|dylib)$", p))


def _sources_for(prereq: str, mdir: Path, root: Path, fileset, by_stem) -> list[str]:
    p = PurePosixPath(prereq)
    if p.suffix in (".o", ".obj", ".lo"):
        stem = p.stem
        cands = [f for f in by_stem.get(stem, []) if PurePosixPath(f).suffix in
                 (".c", ".cc", ".cpp", ".cxx", ".c++", ".m", ".s", ".S")]
        if len(cands) > 1:                              # prefer the one in/under the makefile's dir
            try:
                mrel = mdir.relative_to(root).as_posix()
            except ValueError:
                mrel = ""
            near = [f for f in cands if f.startswith(mrel + "/") or mrel in ("", ".")]
            cands = near or cands
        return cands[:1]
    try:
        rel = (mdir / prereq).resolve().relative_to(root.resolve()).as_posix()
    except ValueError:
        return []
    return [rel] if rel in fileset else []


_FUNC = re.compile(r"\$\((wildcard|patsubst|addprefix|addsuffix|notdir|basename|subst|filter|filter-out|sort|strip)\s+")


def _expand(s: str, vars_: dict, base: Path, depth: int = 0) -> str:
    if depth > 8 or "$" not in s:
        return s
    def var(m):
        name = m.group(1) or m.group(2)
        if ":" in name and "=" in name:                 # $(SRCS:.c=.o)
            v, rule = name.split(":", 1)
            a, b = rule.split("=", 1)
            words = _expand(vars_.get(v, ""), vars_, base, depth + 1).split()
            return " ".join(w[:-len(a)] + b if a and w.endswith(a) else w for w in words)
        return _expand(vars_.get(name, ""), vars_, base, depth + 1)
    def func(m_text):
        m = re.match(r"\$\((\w[\w-]*)\s+(.*)\)$", m_text, re.S)
        if not m:
            return ""
        fn, args = m.group(1), _expand(m.group(2), vars_, base, depth + 1)
        parts = [a.strip() for a in args.split(",")]
        if fn == "wildcard":
            return " ".join(sorted(str(PurePosixPath(os.path.relpath(p, base)))
                                   for pat in args.split() for p in glob.glob(str(base / pat))))
        if fn == "patsubst" and len(parts) == 3:
            pat, rep, words = parts
            pre, _, suf = pat.partition("%")
            rpre, _, rsuf = rep.partition("%")
            return " ".join(rpre + w[len(pre):len(w) - len(suf) if suf else None] + rsuf
                            if w.startswith(pre) and w.endswith(suf) else w for w in words.split())
        if fn == "addprefix" and len(parts) == 2:
            return " ".join(parts[0] + w for w in parts[1].split())
        if fn == "addsuffix" and len(parts) == 2:
            return " ".join(w + parts[0] for w in parts[1].split())
        if fn == "notdir":
            return " ".join(PurePosixPath(w).name for w in args.split())
        if fn == "basename":
            return " ".join(w.rsplit(".", 1)[0] for w in args.split())
        if fn in ("sort", "strip"):
            return " ".join(sorted(set(args.split())) if fn == "sort" else args.split())
        if fn == "subst" and len(parts) == 3:
            return parts[2].replace(parts[0], parts[1])
        if fn in ("filter", "filter-out") and len(parts) == 2:
            pats = [p.replace("%", "*") for p in parts[0].split()]
            keep = [w for w in parts[1].split() if any(fnmatch.fnmatch(w, p) for p in pats)]
            return " ".join(keep if fn == "filter" else [w for w in parts[1].split() if w not in keep])
        return ""
    # functions first (innermost-out), then plain variables
    out, i = "", 0
    while i < len(s):
        if s.startswith("$(", i) and _FUNC.match(s, i):
            depth_p, j = 0, i
            while j < len(s):
                if s[j] == "(":
                    depth_p += 1
                elif s[j] == ")":
                    depth_p -= 1
                    if depth_p == 0:
                        break
                j += 1
            out += func(s[i:j + 1])
            i = j + 1
        else:
            out += s[i]
            i += 1
    out = re.sub(r"\$\(([^()]+)\)|\$\{([^{}]+)\}", var, out)
    return out if "$(" not in out or depth > 6 else _expand(out, vars_, base, depth + 1)


# ── CMakeLists.txt (static, the common commands only) ─────────────────────────
def _cmake(root: Path, cm: Path, fileset, st: Structure):
    text = re.sub(r"#[^\n]*", "", cm.read_text(errors="replace"))
    sets = {m.group(1): m.group(2) for m in re.finditer(r"set\s*\(\s*(\w+)\s+([^)]*)\)", text, re.I)}
    rel_cm = cm.relative_to(root).as_posix()
    def ex(v):
        return re.sub(r"\$\{(\w+)\}", lambda m: sets.get(m.group(1), ""), v)
    for m in re.finditer(r"add_(executable|library)\s*\(\s*([\w.\-]+)([^)]*)\)", text, re.I):
        kind = "executable" if m.group(1).lower() == "executable" else "library"
        tgt = st.targets.setdefault(m.group(2), Target(m.group(2), kind, rel_cm))
        for tok in ex(m.group(3)).split():
            if tok.upper() in ("STATIC", "SHARED", "MODULE", "OBJECT", "INTERFACE", "WIN32", "EXCLUDE_FROM_ALL"):
                continue
            try:
                rel = (cm.parent / tok).resolve().relative_to(root.resolve()).as_posix()
            except ValueError:
                continue
            if rel in fileset:
                tgt.sources.add(rel)
    for m in re.finditer(r"target_link_libraries\s*\(\s*([\w.\-]+)([^)]*)\)", text, re.I):
        if m.group(1) in st.targets:
            st.targets[m.group(1)].links.update(w for w in m.group(2).split()
                                                if w.upper() not in ("PUBLIC", "PRIVATE", "INTERFACE"))
